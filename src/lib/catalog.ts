export function expandAliases(text: string): string {
  let out = ` ${text} `;
  for (const [short, full] of Object.entries(ALIASES)) {
    out = out.split(short).join(full);
  }
  return out.trim();
}

/** Finds the best matching zone for a free-text Hebrew address. */
export function findZone(query: string): Zone | null {
  const q = expandAliases(query).replace(/[,.]/g, " ");
  let best: { zone: Zone; score: number } | null = null;
  for (const zone of ZONES) {
    for (const term of zone.terms) {
      if (q.includes(term)) {
        const score = term.length;
        if (!best || score > best.score) best = { zone, score };
      }
    }
  }
  return best?.zone ?? null;
}
